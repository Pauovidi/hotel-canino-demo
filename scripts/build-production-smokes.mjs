#!/usr/bin/env node

import { mkdir } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outputDir = path.join(rootDir, "scripts", "production-smokes");

export const PRODUCTION_SMOKE_BUNDLES = {
  templates: {
    entry: "scripts/conversation-templates-smoke.ts",
    outfile: "conversation-templates-smoke.mjs",
  },
  identity: {
    entry: "scripts/conversation-identity-smoke.ts",
    outfile: "conversation-identity-smoke.mjs",
  },
  conversation: {
    entry: "scripts/conversation-e2e-smoke.ts",
    outfile: "conversation-e2e-smoke.mjs",
  },
  "conversation-latency": {
    entry: "scripts/conversation-latency-smoke.ts",
    outfile: "conversation-latency-smoke.mjs",
  },
};

function selectedBundles(names) {
  if (!names?.length) {
    return Object.entries(PRODUCTION_SMOKE_BUNDLES);
  }

  return names.map((name) => {
    const bundle = PRODUCTION_SMOKE_BUNDLES[name];
    if (!bundle) {
      throw new Error(`Unknown production smoke bundle: ${name}`);
    }
    return [name, bundle];
  });
}

export function productionSmokeBundlePath(name) {
  const bundle = PRODUCTION_SMOKE_BUNDLES[name];
  if (!bundle) {
    throw new Error(`Unknown production smoke bundle: ${name}`);
  }
  return path.join(outputDir, bundle.outfile);
}

export async function buildProductionSmokes(options = {}) {
  let esbuild;
  try {
    esbuild = await import("esbuild");
  } catch (error) {
    const wrapped = new Error(
      "esbuild is required to build production smoke bundles. Run npm install with devDependencies during build, or use the prebuilt scripts/production-smokes/*.mjs artifacts.",
    );
    wrapped.cause = error;
    throw wrapped;
  }

  await mkdir(outputDir, { recursive: true });
  for (const [name, bundle] of selectedBundles(options.only)) {
    await esbuild.build({
      entryPoints: [path.join(rootDir, bundle.entry)],
      outfile: path.join(outputDir, bundle.outfile),
      bundle: true,
      platform: "node",
      target: "node22",
      format: "esm",
      tsconfig: path.join(rootDir, "tsconfig.json"),
      sourcemap: false,
      logLevel: "silent",
      banner: {
        js: [
          `// Generated by scripts/build-production-smokes.mjs for npm run smoke:${name}. Do not edit by hand.`,
          `import { createRequire as __productionSmokeCreateRequire } from "node:module";`,
          `const require = __productionSmokeCreateRequire(import.meta.url);`,
        ].join("\n"),
      },
    });
    console.log(`[ok] built production smoke bundle: ${bundle.outfile}`);
  }
}

const invokedPath = process.argv[1] ? path.resolve(process.argv[1]) : undefined;
if (invokedPath === fileURLToPath(import.meta.url)) {
  buildProductionSmokes({ only: process.argv.slice(2) })
    .catch((error) => {
      console.error(`[fail] ${error.message}`);
      process.exitCode = 1;
    });
}
